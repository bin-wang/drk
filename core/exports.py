def main():
    assert len(sys.argv) == 2
    # TODO i#10: The current approach of discovering and exporting functions using
    # regular expressions is hacky. It should be replaced when moving to CMake.
    functions = set()
    for path in glob.glob(f"{sys.argv[1]}/*.h"):
        # Skip architecture-specific headers for AArch64 and ARM. Only x86 is
        # supported for now, as this script hardcodes -DX86_64 to extract exports.
        # TODO: Add support for ARM and AArch64 architectures in the future.
        if "aarch64" in path or "arm" in path:
            continue
        code = check_open(
            f"cpp -DX86_64 -DLINUX -Ilib/include -include dr_api.h {path}".split()
        )
        for match in re.findall(
            r"^\s*(?:[a-zA-Z0-9_]+\s+)*([a-zA-Z0-9_]+)\(", code, re.MULTILINE
        ):
            functions.add(match)
    # This is a dirty hack. We don't export certain functions that aren't #
    # implemented. The lib/genapi.pl script should probably be modified to not include
    # functions that are IFDEF'd out.
    functions.difference_update(excluded_functions())
    functions.update(extra_symbols())
    print(
        f"/* This file was automatically generated by {os.path.basename(sys.argv[0])}. */"
    )
    print("#include <linux/module.h>")
    for function in functions:
        print(f"extern void *{function};")
        print(f"EXPORT_SYMBOL_GPL({function});")


if __name__ == "__main__":
    main()
